import assert from "node:assert/strict";
import { locationCoordinates, locationAddressChanged, resetLocationAddressPosition, locationMapApprovalFields } from "../shared/locationMapPosition.js";
import { resolveLocationLocality } from "../base44/shared/locationLocalityResolution.js";
import { newLocationRecord, proposedLocationSnapshot } from "../base44/shared/newLocationProposal.js";
import { getPublicLocationDisclosure } from "../shared/providerPublicTrust.js";
import { loadPublishedLocationsForMap } from "../base44/shared/nationalMapSources.js";
import { buildGoogleMapsDirectionsUrl } from "../src/lib/maps.js";
import { hasPublishedSectionChanges, sameSubmissionPayload } from "../shared/providerWorkspaceSubmissionComparison.js";

const old = { id: "test", address: "Strada Veche 1", city: "Giroc", locality_name: "Giroc", county: "Timiș", county_name: "Timiș", county_code: "TM", locality_siruta_code: "old", lat: 45.7, lng: 21.2, place_id: "old-google", map_precision: "exact", control_status: "verified", profile_control_status: "verified", public_visibility_status: "approved", status: "publicata", active_status: "activa" };
const geo = { siruta_code: "54975", name: "Cluj-Napoca", county_name: "Cluj", county_code: "CJ", uat_code: "54975", uat_name: "Cluj-Napoca" };
let reads = 0;
const svc = { entities: { GeographicLocality: { filter: async (query) => { reads++; assert.equal(query.is_active, true); return query.siruta_code === geo.siruta_code ? [geo] : []; } } } };
const resolved = await resolveLocationLocality(svc, { locality_siruta_code: geo.siruta_code, city: "wrong city", county: "wrong county", address: "Strada Nouă 2" }, { required: true });
assert.equal(resolved.value.city, geo.name);
assert.equal(resolved.value.county, geo.county_name);
assert.equal(resolved.fields.county_code, "CJ");
assert.equal(resolved.fields.uat_code, geo.uat_code);
assert.ok((await resolveLocationLocality(svc, { locality_siruta_code: "missing" })).error);
assert.ok((await resolveLocationLocality(svc, { city: "unverified" })).error);
assert.ok((await resolveLocationLocality(svc, {}, { required: true })).error);
const readCount = reads;
assert.deepEqual((await resolveLocationLocality(svc, { public_phone: "0700000000" })).value, { public_phone: "0700000000" });
assert.equal(reads, readCount, "legacy contact-only updates need no geography lookup");

const edit = resetLocationAddressPosition(old, resolved.value);
assert.equal(locationCoordinates(edit), null);
assert.equal(edit.place_id, "");
assert.equal(edit.map_precision, "approximate");
assert.equal(locationAddressChanged({ city: "Cluj-Napoca" }, old), true);
assert.equal(locationAddressChanged({ address: "  STRADA VECHE 1 " }, old), false);
const legacyFull = { ...old, ...resolved.value, map_precision: "approximate" };
const approved = { ...old, ...resolved.value, ...resolved.fields, ...locationMapApprovalFields(legacyFull, old) };
assert.equal(approved.city, approved.locality_name);
assert.equal(approved.county, approved.county_name);
assert.equal(approved.county_code, "CJ");
assert.equal(approved.lat, null, "repeated legacy coordinates are not the new address");
assert.equal(approved.lng, null);
const publicData = getPublicLocationDisclosure(approved);
assert.equal(publicData.address, "Strada Nouă 2");
assert.equal(publicData.lat, null);
assert.equal(publicData.lng, null);
const route = new URL(buildGoogleMapsDirectionsUrl(approved));
assert.match(route.searchParams.get("destination"), /Strada Nouă 2, Cluj-Napoca, Cluj/);
assert.equal(route.searchParams.has("destination_place_id"), false);

const pin = { ...resolved.value, lat: 46.77, lng: 23.6, map_precision: "exact" };
const confirmed = { ...approved, ...pin, ...locationMapApprovalFields(pin, old) };
assert.deepEqual(locationCoordinates(confirmed), { lat: 46.77, lng: 23.6 });
assert.equal(getPublicLocationDisclosure(confirmed).map_precision, "exact");
assert.equal(hasPublishedSectionChanges("location_details", resolved.value, old), true);
assert.equal(sameSubmissionPayload("location_details", pin, { ...pin, city: "Giroc" }), false);
assert.equal(sameSubmissionPayload("location_details", pin, { ...pin, address: "Unsaved 3" }), false);

const first = newLocationRecord({ proposed: { name: "Optica Test", address: pin.address, ...pin }, geo, organizationId: "org-test" });
assert.equal(first.city, first.locality_name);
assert.equal(first.county, first.county_name);
assert.equal(first.county_code, "CJ");
assert.equal(first.locality_siruta_code, geo.siruta_code);
assert.equal(first.map_precision, "exact");
assert.deepEqual(locationCoordinates(first), { lat: 46.77, lng: 23.6 });
assert.equal(newLocationRecord({ proposed: { address: "Test", lat: 0, lng: 0, map_precision: "exact" }, geo }).lat, undefined);
assert.equal(proposedLocationSnapshot({ ...pin, lat: "46.77" }, geo).lat, 46.77, "duplicate review retains normalized coordinates");
const mapRows = await loadPublishedLocationsForMap({ entities: { ProviderLocation: { filter: async () => [{ ...first, id: "first", status: "publicata" }] } } });
assert.equal(mapRows.locations.length, 1, "the new location has the county code required by the national map");
console.log("location address consistency: official locality, mirrored fields, stale pin removal, routes, public disclosure, new creation and national map passed");
