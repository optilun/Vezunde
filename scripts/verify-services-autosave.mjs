import assert from "node:assert/strict";
import { createDraftSaveController } from "../src/components/workspace/provider/services/draftSaveController.js";
const deferred = () => { let resolve; const promise = new Promise(r => resolve = r); return {promise,resolve}; };
let queue=[], timers={setTimeout:fn=>{queue.push(fn);return fn;},clearTimeout:fn=>{queue=queue.filter(x=>x!==fn);}};
let calls=[], failure=false, held;
const controller=createDraftSaveController({timers});
const record=(signature,baseline="A",dirty=true)=>({signature,baseline,dirty,enabled:true,persist:async()=>{calls.push(signature);if(held){const wait=held;held=null;await wait.promise;}return !failure;}});
controller.update(record("A","A",false));
controller.schedule();assert.equal(queue.length,0,"unchanged offer never creates a draft");
controller.update(record("B"));controller.schedule();
controller.update(record("C"));controller.schedule();assert.equal(queue.length,1,"rapid changes debounce");
queue.shift()();await controller.flush();assert.deepEqual(calls,["C"]);
held=deferred();const wait=held;
controller.update(record("D","C"));const first=controller.flush();
controller.update(record("E","C"));const second=controller.flush();
assert.equal(first,second,"concurrent save/continue shares one write queue");
wait.resolve();assert.equal(await second,true);assert.deepEqual(calls,["C","D","E"]);
held=deferred();const undoWait=held;
controller.update(record("F","E"));const pending=controller.flush();
controller.update(record("E","E",false));undoWait.resolve();
assert.equal(await pending,true);assert.deepEqual(calls.slice(-2),["F","E"],"undo during a write restores the latest selection");
failure=true;controller.update(record("G","E"));assert.equal(await controller.flush(),false);
const failedCount=calls.length;controller.schedule();assert.equal(queue.length,0,"failed snapshot does not loop automatic retries");
failure=false;assert.equal(await controller.flush(),true);assert.equal(calls.length,failedCount+1,"explicit retry resends retained selections");
controller.update(record("SERVER","SERVER",false));await controller.flush();assert.equal(calls.at(-1),"G","reload adopts a confirmed server baseline");
controller.dispose();
const other=createDraftSaveController({timers});other.update(record("A","A",false));await other.flush();assert.equal(calls.at(-1),"G","another location has a separate baseline");
other.dispose();
console.log("Draft autosave: debounce, serialization, in-flight edits, undo, failure, retry, reload and location isolation PASS");
